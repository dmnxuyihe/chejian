import assert from 'node:assert/strict'
import http from 'node:http'
import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'
import { createDatabase } from '../server/database.js'
import { loadConfig } from '../server/config.js'
import { createHandler } from '../server/http.js'
import { templateCsv } from '../src/core/plan-import.js'

const { chromium } = createRequire(import.meta.url)('playwright')
const schema = `pc1_test_${Date.now()}_${process.pid}`
const db = createDatabase({ ...loadConfig(), schema })
const server = http.createServer(createHandler(db))
let browser
const out = process.env.PC1_QA_DIR || 'test-artifacts/pc1-postgres'
await fs.mkdir(out, { recursive: true })
try {
  await db.init()
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const base = `http://127.0.0.1:${server.address().port}`
  browser = await chromium.launch({ channel: 'msedge', headless: true })
  const first = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const second = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const a = await first.newPage(), b = await second.newPage(), errors = []
  for (const page of [a, b]) page.on('pageerror', e => errors.push(e.message))
  await a.goto(`${base}/#/planning/plans`)
  await a.locator('[data-test="pc1-planning"]').waitFor()
  assert.ok((await a.locator('.pc-save-row').innerText()).includes('PostgreSQL'))
  await a.locator('[data-add-plan]').click()
  await a.locator('[data-f="locomotiveNo"]').fill('CRUD-DB')
  await a.locator('[data-f="entry"]').fill('2026-10-30T08:00')
  await a.locator('[data-f="exit"]').fill('2026-11-15T18:00')
  await a.locator('[data-f="priority"]').fill('0')
  await a.locator('[data-modal-confirm]').evaluate(button => { button.click(); button.click() })
  await a.locator('.modal-backdrop').waitFor({ state: 'detached' })
  let crudRow = (await db.pool.query(`SELECT id,details FROM "${schema}".vehicle_repairs WHERE locomotive_no='CRUD-DB'`)).rows
  assert.equal(crudRow.length, 1, '连续点击保存只创建一次')
  assert.equal(crudRow[0].details.priority, 0)
  const crudId = Number(crudRow[0].id)
  await a.locator(`[data-edit-plan="${crudId}"]`).click()
  await a.locator('[data-f="entry"]').fill('2026-11-01T08:00')
  await a.locator('[data-modal-confirm]').click()
  await a.locator('.modal-backdrop').waitFor({ state: 'detached' })
  assert.equal(await a.locator('[data-pc-month]').inputValue(), '2026-11', '跨月编辑后跳到实际入段月')
  await a.reload(); await a.locator('[data-test="pc1-planning"]').waitFor()
  assert.equal(await a.locator('[data-pc-month]').inputValue(), '2026-11', '刷新保留本标签页查看月份')
  await a.locator('[data-pc-month]').fill('2026-11'); await a.locator('[data-pc-month]').dispatchEvent('change')
  assert.equal(await a.locator(`[data-edit-plan="${crudId}"]`).count(), 1)
  await a.locator('[data-add-plan]').click()
  await a.locator('[data-f="locomotiveNo"]').fill(' crud-db ')
  await a.locator('[data-f="entry"]').fill('2026-11-01T12:00')
  await a.locator('[data-f="exit"]').fill('2026-11-20T18:00')
  await a.locator('[data-modal-confirm]').click()
  assert.ok((await a.locator('[data-plan-error]').innerText()).includes('已存在'))
  await a.screenshot({ path: path.join(out, 'plan-duplicate-validation.png'), fullPage: true, animations: 'disabled' })
  assert.equal((await db.read()).snapshot.data.vehicleRepairs.length, 2)
  assert.equal(await a.evaluate(() => window.__APP_STATE__.vehicleRepairs.length), 2, '拒绝重复行不得污染待保存状态')
  await a.locator('[data-modal-confirm]').focus()
  await a.keyboard.press('Tab')
  assert.equal(await a.locator('[data-modal-close]').first().evaluate(el => el === document.activeElement), true, '弹窗Tab应循环留在对话框')
  await a.keyboard.press('Shift+Tab')
  assert.equal(await a.locator('[data-modal-confirm]').evaluate(el => el === document.activeElement), true)
  await a.keyboard.press('Escape')
  assert.equal(await a.locator('[data-add-plan]').evaluate(el => el === document.activeElement), true, '关闭弹窗恢复触发按钮焦点')
  await a.locator(`[data-delete-plan="${crudId}"]`).click()
  await a.locator('[data-modal-close]').last().click()
  assert.equal((await db.read()).snapshot.data.vehicleRepairs.length, 2)
  await a.locator(`[data-delete-plan="${crudId}"]`).click()
  await a.locator('[data-modal-confirm]').click()
  await a.locator('.modal-backdrop').waitFor({ state: 'detached' })
  assert.equal((await db.read()).snapshot.data.vehicleRepairs.length, 1)
  await a.goto(`${base}/#/planning/g2-p2`)
  await a.getByRole('heading', { name: '月度计划日历查询', exact: true }).waitFor()
  assert.equal(await a.locator('[data-add-plan], [data-pc-import], [data-edit-plan], [data-delete-plan]').count(), 0)
  await a.locator('[data-pc-month]').fill('2026-10'); await a.locator('[data-pc-month]').dispatchEvent('change')
  await a.evaluate(() => { document.querySelectorAll('.toast').forEach(t => t.remove()); scrollTo({ top: 0, behavior: 'instant' }) })
  await a.screenshot({ path: path.join(out, 'monthly-query.png'), fullPage: true, animations: 'disabled' })
  await a.goto(`${base}/#/planning/plans`)
  await a.locator('[data-pc-month]').fill('2026-10'); await a.locator('[data-pc-month]').dispatchEvent('change')
  const xlsxDownload = a.waitForEvent('download')
  await a.locator('[data-pc-xlsx-template]').click()
  const xlsx = await xlsxDownload
  assert.equal(xlsx.suggestedFilename(), '月度检修计划导入模板.xlsx')
  const templatePath = path.join(out, '月度检修计划导入模板.xlsx')
  await xlsx.saveAs(templatePath)
  await a.locator('[data-pc-file]').setInputFiles(templatePath)
  await a.locator('.pc-import-panel').waitFor()
  assert.ok((await a.locator('.pc-import-panel').innerText()).includes('2行可导入'))
  await a.locator('[data-pc-confirm-import]').click()
  await a.getByText('导入完成', { exact: true }).waitFor()
  assert.equal((await db.pool.query(`SELECT count(*)::int AS n FROM "${schema}".vehicle_repairs`)).rows[0].n, 3)
  await a.reload()
  await a.locator('[data-test="pc1-planning"]').waitFor()
  assert.equal(await a.locator('.pc-entry.pc-event').count(), 3)
  await b.goto(`${base}/#/planning/plans`)
  await b.locator('[data-test="pc1-planning"]').waitFor()
  assert.equal(await b.locator('.pc-entry.pc-event').count(), 3, '独立浏览器须读到数据库计划')
  assert.equal(await b.evaluate(() => localStorage.getItem('rail-maintenance.pc1-demo.v1')), null)
  await a.locator('[data-pc-file]').setInputFiles({ name: 'duplicate.csv', mimeType: 'text/csv', buffer: Buffer.from(templateCsv) })
  await a.locator('.pc-import-panel').waitFor()
  assert.ok(await a.locator('[data-pc-confirm-import]').isDisabled())
  assert.ok((await a.locator('.pc-import-panel').innerText()).includes('2行重复跳过'))
  await a.locator('[data-pc-file]').setInputFiles({ name: 'broken.xlsx', mimeType: 'application/octet-stream', buffer: Buffer.from('broken') })
  await a.locator('[data-pc-file-status]').filter({ hasText: '导入失败' }).waitFor()
  assert.equal(await a.locator('.pc-import-panel').count(), 0, '新文件损坏时应清除上次预览，防止误导入旧文件')
  assert.equal((await db.read()).snapshot.data.vehicleRepairs.length, 3)
  // Put real schedule results through the same controller used by page changes.
  await a.evaluate(async () => {
    const { submitPlan, runAutoSchedule, publishSchedule } = await import('/src/core/actions.js')
    const s = window.__APP_STATE__
    for (const v of s.vehicleRepairs.filter(v => v.locomotiveNo.startsWith('HXD1C-DEMO'))) { submitPlan(s, v.id); runAutoSchedule(s, v.id); s.selectedVehicleRepairId = v.id; publishSchedule(s) }
    const result = await window.__APP_DEBUG__.getPersistence().save()
    if (!result.ok) throw new Error(result.message)
    window.__APP_DEBUG__.render()
  })
  await b.waitForFunction(() => window.__APP_STATE__.schedules.length === 60, { timeout: 10000 })
  assert.equal(await b.evaluate(() => window.__APP_STATE__.planningView.tab), 'monthly', '页面筛选不应被其他客户端覆盖')
  await b.locator('[data-pc-vehicle="2"]').first().click()
  assert.equal(await b.locator('[data-pc-task]').count(), 20)
  await a.evaluate(async () => {
    const s = window.__APP_STATE__
    s.pc1SchedulePreview = { vehicleRepairIds: [2], schedules: [{ ...s.schedules.find(s => s.vehicleRepairId === 2), plannedStartAt: '2026-10-29T08:00:00', plannedEndAt: '2026-10-29T09:00:00', isLocked: true }] }
    await window.__APP_DEBUG__.getPersistence().save()
    window.__APP_DEBUG__.render()
  })
  await b.waitForFunction(() => !!window.__APP_STATE__.pc1SchedulePreview, { timeout: 10000 })
  assert.equal(await b.locator('[data-pc-task]').count(), 1)
  assert.equal(await b.locator('.pc-event.pc-preview').count(), 1)
  await b.reload(); await b.locator('[data-test="pc1-planning"]').waitFor()
  assert.equal(await b.evaluate(() => window.__APP_STATE__.pc1SchedulePreview.schedules[0].isLocked), true)
  assert.equal(await b.locator('[data-pc-detail-vehicle]').inputValue(), '2', '刷新保留本标签页车辆选择')
  // Client A posts with a stale revision: show the conflict, keep edits and DB.
  await b.evaluate(() => { window.__APP_STATE__.vehicleRepairs[0].remark = 'concurrent-unsaved'; })
  await a.evaluate(async () => { window.__APP_STATE__.vehicleRepairs[0].remark = 'database-new'; await window.__APP_DEBUG__.getPersistence().save() })
  const conflict = await b.evaluate(async () => { const p = window.__APP_DEBUG__.getPersistence(); return p.save() })
  assert.equal(conflict.ok, false)
  assert.ok((await b.locator('.pc-save-row').innerText()).includes('冲突'))
  assert.equal(await b.evaluate(() => window.__APP_STATE__.vehicleRepairs[0].remark), 'concurrent-unsaved')
  await b.locator('[data-pc-data-tools]').click()
  await b.locator('[data-pc-db-reload]').click()
  const backupDownload = b.waitForEvent('download')
  await b.locator('[data-pc-confirm-data]').click()
  await backupDownload
  await b.waitForFunction(() => window.__APP_STATE__.vehicleRepairs[0].remark === 'database-new')
  await b.evaluate(() => { document.querySelectorAll('.toast').forEach(t => t.remove()); scrollTo({ top: 0, behavior: 'instant' }) })
  await b.screenshot({ path: path.join(out, 'postgres-connected.png'), fullPage: true, animations: 'disabled' })
  // A failed write is never reported as saved and can be retried without losing state.
  await a.route('**/api/state', route => route.request().method() === 'PUT' ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"测试数据库中断"}' }) : route.continue())
  const failed = await a.evaluate(async () => { window.__APP_STATE__.vehicleRepairs[0].remark = 'retry-after-outage'; return window.__APP_DEBUG__.getPersistence().save() })
  assert.equal(failed.ok, false)
  assert.ok((await a.locator('.pc-save-row').innerText()).includes('未保存'))
  await a.unroute('**/api/state')
  assert.ok((await a.evaluate(() => window.__APP_DEBUG__.getPersistence().save())).ok)
  assert.equal((await db.read()).snapshot.data.vehicleRepairs[0].remark, 'retry-after-outage')
  await b.evaluate(() => window.__APP_DEBUG__.getPersistence().poll())
  await b.evaluate(async () => {
    const p = window.__APP_DEBUG__.getPersistence()
    const backup = JSON.parse(p.export())
    backup.data.vehicleRepairs[0].remark = 'migrated-from-local'
    localStorage.setItem('rail-maintenance.pc1-demo.v1', JSON.stringify(backup))
    window.__APP_DEBUG__.render()
  })
  await b.locator('[data-pc-migrate]').click()
  const migrateDownload = b.waitForEvent('download')
  await b.locator('[data-pc-confirm-data]').click(); await migrateDownload
  await b.waitForFunction(() => window.__APP_STATE__.vehicleRepairs[0].remark === 'migrated-from-local')
  assert.equal((await db.read()).snapshot.data.vehicleRepairs[0].remark, 'migrated-from-local')
  await b.locator('[data-pc-reset]').click()
  const resetDownload = b.waitForEvent('download')
  await b.locator('[data-pc-confirm-data]').click(); await resetDownload
  await b.waitForFunction(() => window.__APP_STATE__.vehicleRepairs.length === 1)
  assert.equal((await db.read()).snapshot.data.vehicleRepairs.length, 1)
  await b.locator('[data-pc-undo-data]').click()
  await b.waitForFunction(() => window.__APP_STATE__.vehicleRepairs.length === 3)
  assert.equal((await db.read()).snapshot.data.vehicleRepairs.length, 3)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ passed: true, checks: ['plan CRUD -> PostgreSQL', 'double-submit guard and zero priority', 'cross-month edit', 'duplicate create/import rejected', 'delete confirm/cancel', 'query route', 'downloaded XLSX -> import -> PostgreSQL', 'refresh persistence', 'independent browser reads', 'cross-client schedule and preview sync', 'locked draft reload', 'stale-writer conflict and recover', 'failed save and retry', 'local data migration', 'database reset and undo'], screenshots: out }, null, 2))
} finally {
  await browser?.close()
  await new Promise(resolve => server.close(resolve))
  assert.ok(/^pc1_test_\d+_\d+$/.test(schema))
  await db.pool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`)
  await db.close()
}
