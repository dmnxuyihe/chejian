-- 月度检修计划数据库初始化（独立演示版）
-- 适用：PostgreSQL 14+
-- 范围：月计划导入/纠错、编制、车辆排程、版本、审批、附件、交验统计
-- 说明：
--   1. 本文件不修改既有 vehicle_repair、vehicle_repair_schedule、用户、机车等表。
--   2. existing_*_id 字段用于后续关联现有系统；为了让本脚本可独立执行，暂不设置跨表外键。
--   3. 演示数据统一使用 2026-10，覆盖草稿、已提报、已发布、调整、驳回、导入错误和复验场景。

BEGIN;

-- 与主项目保持一致，默认安装到 pc1 schema。
-- 如项目使用其他 PC1_DB_SCHEMA，请通过 scripts/init-monthly-plan.mjs 执行，
-- 运行器会在事务开始前将本行替换为实际 schema。
CREATE SCHEMA IF NOT EXISTS pc1;
SET LOCAL search_path TO pc1, public;

-- ============================================================
-- 1. 导入批次与逐行纠错
-- ============================================================

CREATE TABLE IF NOT EXISTS monthly_plan_import_batch (
    batch_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_month           DATE NOT NULL,
    source_type          VARCHAR(20) NOT NULL,
    source_system        VARCHAR(50),
    external_batch_no    VARCHAR(100),
    file_name            VARCHAR(255),
    file_checksum        VARCHAR(128),
    total_count          INTEGER NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    success_count        INTEGER NOT NULL DEFAULT 0 CHECK (success_count >= 0),
    error_count          INTEGER NOT NULL DEFAULT 0 CHECK (error_count >= 0),
    batch_status         VARCHAR(20) NOT NULL,
    error_summary        TEXT,
    imported_by          BIGINT,
    started_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_monthly_import_month CHECK (plan_month = date_trunc('month', plan_month)::date),
    CONSTRAINT ck_monthly_import_source CHECK (source_type IN ('EXCEL', 'CSV', 'JMIS', 'MANUAL')),
    CONSTRAINT ck_monthly_import_status CHECK (batch_status IN ('VALIDATING', 'SUCCESS', 'PARTIAL_SUCCESS', 'FAILED')),
    CONSTRAINT ck_monthly_import_counts CHECK (success_count + error_count <= total_count)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_monthly_import_checksum
    ON monthly_plan_import_batch(file_checksum)
    WHERE file_checksum IS NOT NULL;

CREATE TABLE IF NOT EXISTS monthly_plan_import_item (
    import_item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id             BIGINT NOT NULL REFERENCES monthly_plan_import_batch(batch_id) ON DELETE CASCADE,
    source_row_no        INTEGER NOT NULL CHECK (source_row_no > 0),
    external_plan_id     VARCHAR(100),
    raw_payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
    validation_status    VARCHAR(20) NOT NULL,
    error_code           VARCHAR(50),
    error_message        TEXT,
    corrected_payload    JSONB,
    corrected_by         BIGINT,
    corrected_at         TIMESTAMPTZ,
    plan_vehicle_id      BIGINT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_monthly_import_row UNIQUE (batch_id, source_row_no),
    CONSTRAINT ck_monthly_import_item_status CHECK (validation_status IN ('PENDING', 'VALID', 'ERROR', 'CORRECTED')),
    CONSTRAINT ck_monthly_import_item_error CHECK (
        validation_status <> 'ERROR' OR error_message IS NOT NULL
    ),
    CONSTRAINT ck_monthly_import_item_corrected CHECK (
        validation_status <> 'CORRECTED'
        OR (corrected_payload IS NOT NULL AND corrected_by IS NOT NULL AND corrected_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS ix_monthly_import_item_status
    ON monthly_plan_import_item(batch_id, validation_status);

-- ============================================================
-- 2. 月计划、版本与车辆明细
-- ============================================================

CREATE TABLE IF NOT EXISTS monthly_plan (
    monthly_plan_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_month           DATE NOT NULL,
    plan_name            VARCHAR(100) NOT NULL,
    plan_status          VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    current_version_id   BIGINT,
    source_type          VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    source_batch_id      BIGINT REFERENCES monthly_plan_import_batch(batch_id) ON DELETE SET NULL,
    created_by           BIGINT NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by           BIGINT,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_by           BIGINT,
    deleted_at           TIMESTAMPTZ,
    CONSTRAINT ck_monthly_plan_month CHECK (plan_month = date_trunc('month', plan_month)::date),
    CONSTRAINT ck_monthly_plan_status CHECK (plan_status IN ('DRAFT', 'IN_APPROVAL', 'PUBLISHED', 'REJECTED', 'VOID')),
    CONSTRAINT ck_monthly_plan_source CHECK (source_type IN ('EXCEL', 'CSV', 'JMIS', 'MANUAL')),
    CONSTRAINT ck_monthly_plan_soft_delete CHECK (
        (deleted_at IS NULL AND deleted_by IS NULL) OR (deleted_at IS NOT NULL AND deleted_by IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_monthly_plan_active_month
    ON monthly_plan(plan_month)
    WHERE deleted_at IS NULL AND plan_status <> 'VOID';

CREATE TABLE IF NOT EXISTS monthly_plan_version (
    version_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monthly_plan_id      BIGINT NOT NULL REFERENCES monthly_plan(monthly_plan_id) ON DELETE RESTRICT,
    version_no           INTEGER NOT NULL CHECK (version_no > 0),
    version_type         VARCHAR(20) NOT NULL,
    parent_version_id    BIGINT REFERENCES monthly_plan_version(version_id) ON DELETE RESTRICT,
    version_status       VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    adjustment_reason    TEXT,
    change_summary       TEXT,
    created_by           BIGINT NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_by         BIGINT,
    submitted_at         TIMESTAMPTZ,
    published_by         BIGINT,
    published_at         TIMESTAMPTZ,
    effective_at         TIMESTAMPTZ,
    CONSTRAINT uk_monthly_plan_version UNIQUE (monthly_plan_id, version_no),
    CONSTRAINT ck_monthly_version_type CHECK (version_type IN ('INITIAL', 'ADJUSTMENT')),
    CONSTRAINT ck_monthly_version_status CHECK (version_status IN ('DRAFT', 'SUBMITTED', 'REVIEWED', 'PUBLISHED', 'REJECTED', 'SUPERSEDED')),
    CONSTRAINT ck_monthly_adjustment_reason CHECK (
        version_type <> 'ADJUSTMENT'
        OR (parent_version_id IS NOT NULL AND nullif(btrim(adjustment_reason), '') IS NOT NULL)
    ),
    CONSTRAINT ck_monthly_submitted_fields CHECK (
        (submitted_by IS NULL AND submitted_at IS NULL) OR (submitted_by IS NOT NULL AND submitted_at IS NOT NULL)
    ),
    CONSTRAINT ck_monthly_published_fields CHECK (
        (published_by IS NULL AND published_at IS NULL) OR (published_by IS NOT NULL AND published_at IS NOT NULL)
    )
);

ALTER TABLE monthly_plan
    DROP CONSTRAINT IF EXISTS fk_monthly_plan_current_version;
ALTER TABLE monthly_plan
    ADD CONSTRAINT fk_monthly_plan_current_version
    FOREIGN KEY (current_version_id) REFERENCES monthly_plan_version(version_id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE INDEX IF NOT EXISTS ix_monthly_plan_version_status
    ON monthly_plan_version(monthly_plan_id, version_status);

CREATE TABLE IF NOT EXISTS monthly_plan_vehicle (
    plan_vehicle_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id           BIGINT NOT NULL REFERENCES monthly_plan_version(version_id) ON DELETE CASCADE,
    existing_vehicle_repair_id BIGINT,
    existing_locomotive_id BIGINT,
    locomotive_type      VARCHAR(50) NOT NULL,
    locomotive_no        VARCHAR(50) NOT NULL,
    repair_program_code  VARCHAR(50) NOT NULL,
    repair_sequence      INTEGER NOT NULL DEFAULT 1 CHECK (repair_sequence > 0),
    owner_bureau         VARCHAR(100),
    owner_depot          VARCHAR(100) NOT NULL,
    planned_entry_at     TIMESTAMPTZ NOT NULL,
    planned_exit_at      TIMESTAMPTZ NOT NULL,
    mileage_km           NUMERIC(12,2) CHECK (mileage_km IS NULL OR mileage_km >= 0),
    priority             INTEGER NOT NULL DEFAULT 0,
    row_source           VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    external_plan_id     VARCHAR(100),
    remark               TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_monthly_plan_vehicle UNIQUE (version_id, locomotive_no),
    CONSTRAINT ck_monthly_vehicle_dates CHECK (planned_exit_at > planned_entry_at),
    CONSTRAINT ck_monthly_vehicle_source CHECK (row_source IN ('EXCEL', 'CSV', 'JMIS', 'MANUAL'))
);

CREATE INDEX IF NOT EXISTS ix_monthly_vehicle_query
    ON monthly_plan_vehicle(version_id, owner_depot, repair_program_code);
CREATE INDEX IF NOT EXISTS ix_monthly_vehicle_locomotive
    ON monthly_plan_vehicle(locomotive_no, planned_entry_at);

-- 回填导入明细生成的月计划车辆记录。
ALTER TABLE monthly_plan_import_item
    DROP CONSTRAINT IF EXISTS fk_monthly_import_plan_vehicle;
ALTER TABLE monthly_plan_import_item
    ADD CONSTRAINT fk_monthly_import_plan_vehicle
    FOREIGN KEY (plan_vehicle_id) REFERENCES monthly_plan_vehicle(plan_vehicle_id) ON DELETE SET NULL;

-- ============================================================
-- 3. 车辆排程快照
-- 提报时冻结本版排程，审批人审核的正是这里的内容。
-- ============================================================

CREATE TABLE IF NOT EXISTS monthly_plan_schedule_snapshot (
    snapshot_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id           BIGINT NOT NULL REFERENCES monthly_plan_version(version_id) ON DELETE CASCADE,
    plan_vehicle_id      BIGINT NOT NULL REFERENCES monthly_plan_vehicle(plan_vehicle_id) ON DELETE CASCADE,
    existing_schedule_id BIGINT,
    schedule_no          VARCHAR(50) NOT NULL,
    planned_entry_at     TIMESTAMPTZ NOT NULL,
    planned_start_at     TIMESTAMPTZ NOT NULL,
    planned_finish_at    TIMESTAMPTZ NOT NULL,
    planned_exit_at      TIMESTAMPTZ NOT NULL,
    workstation_code     VARCHAR(50),
    workstation_name     VARCHAR(100),
    team_code            VARCHAR(50),
    team_name            VARCHAR(100),
    conflict_status      VARCHAR(20) NOT NULL DEFAULT 'NONE',
    conflict_message     TEXT,
    schedule_data        JSONB NOT NULL DEFAULT '{}'::jsonb,
    frozen_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_monthly_schedule_no UNIQUE (version_id, schedule_no),
    CONSTRAINT ck_monthly_schedule_time CHECK (
        planned_entry_at <= planned_start_at
        AND planned_start_at < planned_finish_at
        AND planned_finish_at <= planned_exit_at
    ),
    CONSTRAINT ck_monthly_schedule_conflict CHECK (conflict_status IN ('NONE', 'WARNING', 'BLOCKED'))
);

CREATE INDEX IF NOT EXISTS ix_monthly_schedule_vehicle
    ON monthly_plan_schedule_snapshot(plan_vehicle_id);
CREATE INDEX IF NOT EXISTS ix_monthly_schedule_resource
    ON monthly_plan_schedule_snapshot(workstation_code, planned_start_at, planned_finish_at);

-- ============================================================
-- 4. 审批实例与操作流水
-- ============================================================

CREATE TABLE IF NOT EXISTS plan_approval_instance (
    approval_instance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type        VARCHAR(30) NOT NULL,
    business_id          BIGINT NOT NULL,
    approval_round       INTEGER NOT NULL DEFAULT 1 CHECK (approval_round > 0),
    current_node         VARCHAR(30),
    approval_status      VARCHAR(20) NOT NULL,
    submitted_by         BIGINT NOT NULL,
    submitted_at         TIMESTAMPTZ NOT NULL,
    completed_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_plan_approval_round UNIQUE (business_type, business_id, approval_round),
    CONSTRAINT ck_plan_approval_business CHECK (business_type IN ('MONTHLY_PLAN')),
    CONSTRAINT ck_plan_approval_node CHECK (current_node IS NULL OR current_node IN ('SECTION_REVIEW', 'DEPUT_APPROVAL', 'COMPLETED')),
    CONSTRAINT ck_plan_approval_status CHECK (approval_status IN ('IN_PROGRESS', 'APPROVED', 'REJECTED', 'WITHDRAWN'))
);

CREATE INDEX IF NOT EXISTS ix_plan_approval_todo
    ON plan_approval_instance(approval_status, current_node);

CREATE TABLE IF NOT EXISTS plan_approval_action (
    approval_action_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_instance_id BIGINT NOT NULL REFERENCES plan_approval_instance(approval_instance_id) ON DELETE CASCADE,
    node_code            VARCHAR(30) NOT NULL,
    action_type          VARCHAR(20) NOT NULL,
    operator_id          BIGINT NOT NULL,
    operator_name        VARCHAR(100) NOT NULL,
    operator_role        VARCHAR(100) NOT NULL,
    approval_opinion     TEXT,
    action_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_plan_approval_action_node CHECK (node_code IN ('PLAN_EDITOR', 'SECTION_REVIEW', 'DEPUT_APPROVAL')),
    CONSTRAINT ck_plan_approval_action_type CHECK (action_type IN ('SUBMIT', 'APPROVE', 'REJECT', 'WITHDRAW', 'PUBLISH'))
);

CREATE INDEX IF NOT EXISTS ix_plan_approval_action_time
    ON plan_approval_action(approval_instance_id, action_at);

-- ============================================================
-- 5. 通用附件
-- ============================================================

CREATE TABLE IF NOT EXISTS plan_attachment (
    attachment_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_type        VARCHAR(30) NOT NULL,
    business_id          BIGINT NOT NULL,
    attachment_category  VARCHAR(30) NOT NULL,
    file_name            VARCHAR(255) NOT NULL,
    mime_type            VARCHAR(100),
    file_size            BIGINT CHECK (file_size IS NULL OR file_size >= 0),
    storage_key          VARCHAR(500) NOT NULL,
    file_checksum        VARCHAR(128),
    uploaded_by          BIGINT NOT NULL,
    uploaded_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_by           BIGINT,
    deleted_at           TIMESTAMPTZ,
    CONSTRAINT ck_plan_attachment_business CHECK (business_type IN ('MONTHLY_PLAN_VERSION', 'APPROVAL', 'VERIFICATION', 'IMPORT_BATCH')),
    CONSTRAINT ck_plan_attachment_category CHECK (attachment_category IN ('SOURCE_FILE', 'PLAN_FILE', 'APPROVAL_FILE', 'VERIFICATION_FILE', 'ADJUSTMENT_FILE'))
);

CREATE INDEX IF NOT EXISTS ix_plan_attachment_business
    ON plan_attachment(business_type, business_id)
    WHERE deleted_at IS NULL;

-- ============================================================
-- 6. 月度交验记录（支持不合格后复验）
-- ============================================================

CREATE TABLE IF NOT EXISTS monthly_plan_verification (
    verification_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_vehicle_id      BIGINT NOT NULL REFERENCES monthly_plan_vehicle(plan_vehicle_id) ON DELETE RESTRICT,
    existing_vehicle_repair_id BIGINT,
    verification_no      VARCHAR(50) NOT NULL UNIQUE,
    attempt_no           INTEGER NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
    verification_at      TIMESTAMPTZ NOT NULL,
    commissioning_depot  VARCHAR(100) NOT NULL,
    verification_result  VARCHAR(20) NOT NULL,
    inspector_id         BIGINT,
    inspector_name       VARCHAR(100) NOT NULL,
    failure_reason       TEXT,
    reinspection_of      BIGINT REFERENCES monthly_plan_verification(verification_id) ON DELETE RESTRICT,
    remark               TEXT,
    created_by           BIGINT NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_monthly_verification_attempt UNIQUE (plan_vehicle_id, attempt_no),
    CONSTRAINT ck_monthly_verification_result CHECK (verification_result IN ('PENDING', 'PASSED', 'FAILED')),
    CONSTRAINT ck_monthly_verification_failure CHECK (
        verification_result <> 'FAILED' OR nullif(btrim(failure_reason), '') IS NOT NULL
    ),
    CONSTRAINT ck_monthly_verification_reinspection CHECK (
        attempt_no = 1 OR reinspection_of IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS ix_monthly_verification_stats
    ON monthly_plan_verification(verification_at, commissioning_depot, verification_result);

